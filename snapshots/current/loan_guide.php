<script>
    (function () {
        var mq = window.matchMedia('(max-width: 768px)');
        var viewer = document.getElementById('contractViewer');
        var img = document.getElementById('contractViewerImg');
        var closeBtn = document.getElementById('contractViewerClose');
        var zoomInBtn = document.getElementById('contractViewerZoomIn');
        var zoomOutBtn = document.getElementById('contractViewerZoomOut');

        if (!viewer || !img || !closeBtn) return;

        /* 확대 상태 : s = 배율, x/y = 이미지 위치 */
        var s = 1, minS = 1, maxS = 3, x = 0, y = 0;
        var natW = 0, natH = 0;
        var touchState = null;
        var lastTap = 0;

        function vw() { return viewer.clientWidth; }
        function vh() { return viewer.clientHeight; }

        /* 이미지가 화면 밖으로 벗어나지 않게 위치 보정 */
        function clampPos() {
            var w = natW * s;
            var h = natH * s;

            if (w <= vw()) {
                x = (vw() - w) / 2;
            } else {
                x = Math.min(0, Math.max(vw() - w, x));
            }

            if (h <= vh()) {
                y = (vh() - h) / 2;
            } else {
                y = Math.min(0, Math.max(vh() - h, y));
            }
        }

        function apply() {
            clampPos();
            img.style.transform = 'translate(' + x + 'px, ' + y + 'px) scale(' + s + ')';
        }

        /* 기준점(cx, cy)을 중심으로 확대/축소 */
        function zoomTo(ns, cx, cy) {
            ns = Math.max(minS, Math.min(maxS, ns));
            x = cx - (cx - x) * (ns / s);
            y = cy - (cy - y) * (ns / s);
            s = ns;
            apply();
        }

        function openViewer(src, alt) {
            img.onload = function () {
                natW = img.naturalWidth;
                natH = img.naturalHeight;

                /* 처음엔 화면 폭에 맞춤, 최대 원본의 3배까지 확대 */
                minS = vw() / natW;
                maxS = Math.max(minS * 4, 3);
                s = minS;
                x = 0;
                y = 0;
                apply();
            };

            img.alt = alt;
            img.src = src;
            viewer.classList.add('is-open');
            document.body.classList.add('viewer-open');
        }

        function closeViewer() {
            viewer.classList.remove('is-open');
            document.body.classList.remove('viewer-open');
            img.onload = null;
            img.src = '';
            touchState = null;
        }

        function dist(t) {
            var dx = t[0].clientX - t[1].clientX;
            var dy = t[0].clientY - t[1].clientY;
            return Math.sqrt(dx * dx + dy * dy);
        }

        function mid(t) {
            return {
                x: (t[0].clientX + t[1].clientX) / 2,
                y: (t[0].clientY + t[1].clientY) / 2
            };
        }

        /* 모바일에서만 확대 보기 (PC는 클릭 반응 없음) */
        document.querySelectorAll('.contract-guide-item img').forEach(function (el) {
            el.addEventListener('click', function () {
                if (!mq.matches) return;
                openViewer(el.src, el.alt);
            });
        });

        /* 터치 : 두 손가락 확대/축소, 한 손가락 이동, 두 번 탭 확대/원래대로 */
        viewer.addEventListener('touchstart', function (e) {
            if (e.target.closest('button')) return;

            if (e.touches.length === 2) {
                var m = mid(e.touches);
                touchState = { mode: 'pinch', d: dist(e.touches), s: s, cx: m.x, cy: m.y, x: x, y: y };
            } else if (e.touches.length === 1) {
                var t = e.touches[0];
                var now = Date.now();

                if (now - lastTap < 300) {
                    if (s > minS * 1.05) {
                        zoomTo(minS, t.clientX, t.clientY);
                    } else {
                        zoomTo(minS * 2.5, t.clientX, t.clientY);
                    }
                    lastTap = 0;
                    touchState = null;
                    return;
                }

                lastTap = now;
                touchState = { mode: 'pan', px: t.clientX, py: t.clientY, x: x, y: y };
            }
        }, { passive: false });

        viewer.addEventListener('touchmove', function (e) {
            if (!touchState) return;
            e.preventDefault();

            if (touchState.mode === 'pinch' && e.touches.length === 2) {
                var ns = touchState.s * dist(e.touches) / touchState.d;
                ns = Math.max(minS, Math.min(maxS, ns));

                var m = mid(e.touches);
                var ratio = ns / touchState.s;

                x = m.x - (touchState.cx - touchState.x) * ratio;
                y = m.y - (touchState.cy - touchState.y) * ratio;
                s = ns;
                apply();
            } else if (touchState.mode === 'pan' && e.touches.length === 1) {
                var t = e.touches[0];
                x = touchState.x + (t.clientX - touchState.px);
                y = touchState.y + (t.clientY - touchState.py);
                apply();
            }
        }, { passive: false });

        viewer.addEventListener('touchend', function (e) {
            if (e.touches.length === 1) {
                var t = e.touches[0];
                touchState = { mode: 'pan', px: t.clientX, py: t.clientY, x: x, y: y };
            } else if (e.touches.length === 0) {
                touchState = null;
            }
        });

        /* 버튼 : 화면 가운데 기준 확대/축소 */
        zoomInBtn.addEventListener('click', function () {
            zoomTo(s * 1.5, vw() / 2, vh() / 2);
        });

        zoomOutBtn.addEventListener('click', function () {
            zoomTo(s / 1.5, vw() / 2, vh() / 2);
        });

        closeBtn.addEventListener('click', closeViewer);

        window.addEventListener('resize', function () {
            if (!viewer.classList.contains('is-open') || !natW) return;
            minS = vw() / natW;
            if (s < minS) s = minS;
            apply();
        });
    })();
</script>

