    <img src="" alt="" class="contract-viewer-img" id="contractViewerImg">
    <button type="button" class="contract-viewer-btn contract-viewer-close" id="contractViewerClose" aria-label="닫기">×</button>
    <button type="button" class="contract-viewer-btn contract-viewer-zoomin" id="contractViewerZoomIn" aria-label="확대">+</button>
    <button type="button" class="contract-viewer-btn contract-viewer-zoomout" id="contractViewerZoomOut" aria-label="축소">−</button>
